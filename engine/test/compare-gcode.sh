#!/usr/bin/env bash
# Vergleicht zwei OrcaSlicer-G-Code-Dateien.
#
# Hauptmetrik seit 2026-10-24: der EXECUTABLE_BLOCK muss sha256-identisch
# sein. Dort steckt die eigentliche Slice-Logik (G-Moves + Metadata-Marker).
# Header und CONFIG_BLOCK unterscheiden sich systematisch zwischen GUI-
# Export und unserem CLI (Thumbnail, Block-Reihenfolge, einzelne Metadaten
# wie `model label id`) – siehe docs/engine-integration.md Abschnitt
# "Nachweislauf".
#
# Als Fallback zeigt das Script auch den Ganz-Datei-Hash (nach Entfernen
# der einzigen zeitlich variablen Header-Zeile), damit man weiss, ob
# Rest-Unterschiede vorliegen.
#
# Usage: compare-gcode.sh ref.gcode ours.gcode
#   exit 0 wenn EXECUTABLE_BLOCK identisch, sonst 1

set -euo pipefail

if [ "$#" -ne 2 ]; then
    echo "Usage: $0 ref.gcode ours.gcode" >&2
    exit 2
fi

REF="$1"
OURS="$2"

TMPDIR=$(mktemp -d)
trap "rm -rf $TMPDIR" EXIT

# EXECUTABLE_BLOCK extrahieren
awk '/^; EXECUTABLE_BLOCK_START/,/^; EXECUTABLE_BLOCK_END/' "$REF"  > "$TMPDIR/ref-exec.g"
awk '/^; EXECUTABLE_BLOCK_START/,/^; EXECUTABLE_BLOCK_END/' "$OURS" > "$TMPDIR/our-exec.g"

sha_ref_exec=$(sha256sum "$TMPDIR/ref-exec.g" | awk '{print $1}')
sha_our_exec=$(sha256sum "$TMPDIR/our-exec.g" | awk '{print $1}')
ln_ref_exec=$(wc -l < "$TMPDIR/ref-exec.g")
ln_our_exec=$(wc -l < "$TMPDIR/our-exec.g")

echo "=== EXECUTABLE_BLOCK ==="
printf "  ref : %s  (%s Zeilen)\n" "$sha_ref_exec" "$ln_ref_exec"
printf "  ours: %s  (%s Zeilen)\n" "$sha_our_exec" "$ln_our_exec"

exec_match=0
if [ "$sha_ref_exec" = "$sha_our_exec" ]; then
    echo "  → IDENTISCH"
    exec_match=1
else
    echo "  → UNTERSCHIEDLICH"
    echo "  erste 40 Zeilen Diff:"
    diff "$TMPDIR/ref-exec.g" "$TMPDIR/our-exec.g" | head -40 | sed 's/^/    /'
fi

# Zusatzinfo: Ganzdatei-Hash nach Entfernen der zeitlichen Zeile
FILTER_REGEX='^; generated by OrcaSlicer .* on [0-9-]+ at [0-9:]+$'
sha_ref_full=$(grep -vE "$FILTER_REGEX" "$REF"  | sha256sum | awk '{print $1}')
sha_our_full=$(grep -vE "$FILTER_REGEX" "$OURS" | sha256sum | awk '{print $1}')
echo
echo "=== Gesamt-Datei (gefiltert, nur ohne Header-Timestamp) ==="
printf "  ref : %s\n" "$sha_ref_full"
printf "  ours: %s\n" "$sha_our_full"
[ "$sha_ref_full" = "$sha_our_full" ] && echo "  → IDENTISCH" || echo "  → UNTERSCHIEDLICH (Header/Config/Thumbnail erwartet)"

[ "$exec_match" = "1" ] && exit 0 || exit 1
