#!/usr/bin/env bash
# Vertragstest fuer Phase 4.4 (Filament-Overrides pro Fach).
# Zeigt lokal auf x86, dass drei typische Filament-opt_keys im G-Code
# ankommen – ohne Poco/ADB. Spiegelt die Checks aus
# cli-contract-arm64.sh "=== 6 Filament-Overrides".
#
# Faelle:
#   - nozzle_temperature=260                   -> M104 S260 ; set nozzle temperature
#   - hot_plate_temp_initial_layer=88 (bed B)  -> M190 S88 A am Pre-Heat
#   - retraction_length=2.4                    -> G1 E-2.4-Zuege
#   - Baseline-Doppel-Lauf byte-identisch (Null-Change-Garantie)
#
# Benutzt das Elegoo-PETG-Profil, weil das die bed_type-abhaengigen
# Felder (hot_plate_temp*, textured_plate_temp*) komplett belegt.

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CLI="${PROJECT_ROOT}/engine/bin/handslice-cli-x86"
STL="${PROJECT_ROOT}/engine/test/cube_notched_20mm_centered_cc2.stl"
RES="${PROJECT_ROOT}/engine/OrcaSlicer/resources"
PROF="${RES}/profiles/Elegoo"
MACH="${PROF}/machine/ECC2/Elegoo Centauri Carbon 2 0.4 nozzle.json"
PROC="${PROF}/process/ECC2/0.20mm Standard @Elegoo CC2 0.4 nozzle.json"
FIL="${PROF}/filament/ECC2/Elegoo PETG @ECC2.json"
[[ -x "${CLI}" ]] || { echo "FEHLT: ${CLI}" >&2; exit 2; }

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

run() {
    local out="$1"; shift
    "${CLI}" --machine "${MACH}" --process "${PROC}" --filament "${FIL}" \
        --resources "${RES}" --output "${out}" --bed-type B --quiet \
        --no-center "$@" "${STL}" > /dev/null
}

run "${TMP}/fbase.gcode"
run "${TMP}/fbase2.gcode"
run "${TMP}/fn.gcode"  --overrides '{"nozzle_temperature":"260"}'
run "${TMP}/fb.gcode"  --overrides '{"hot_plate_temp_initial_layer":"88"}'
run "${TMP}/fr.gcode"  --overrides '{"retraction_length":"2.4"}'

python3 <<PY
import hashlib, re, sys
def md5_sanitized(p):
    """md5 des G-Code ohne die eine ';generated by …'-Header-Zeile mit
    Timestamp (die ist bei jedem Lauf anders und sagt nichts ueber das
    Slicing)."""
    h = hashlib.md5()
    for line in open(p, 'rb'):
        if line.startswith(b'; generated by OrcaSlicer'):
            h.update(b'; generated by OrcaSlicer\n')
        else:
            h.update(line)
    return h.hexdigest()

mb1 = md5_sanitized('${TMP}/fbase.gcode')
mb2 = md5_sanitized('${TMP}/fbase2.gcode')
if mb1 != mb2:
    print(f'FAIL: Baseline nicht byte-identisch ({mb1[:10]} vs {mb2[:10]})', file=sys.stderr)
    sys.exit(1)
print(f'  Baseline byte-identisch (md5 {mb1[:10]}… ohne Timestamp)')

def grep_lines(p, pattern):
    r = re.compile(pattern)
    return [ln.rstrip() for ln in open(p) if r.search(ln)]

# 1) nozzle_temperature
nl = grep_lines('${TMP}/fn.gcode', r'^M104 S\d+ ; set nozzle temperature')
if not any('S260' in l for l in nl):
    print('FAIL: M104 S260 nicht im G-Code', file=sys.stderr); sys.exit(1)
print('  nozzle=260 →', next(l for l in nl if 'S260' in l))

# 2) hot_plate_temp_initial_layer
bl = grep_lines('${TMP}/fb.gcode', r'^M190 S\d+ A')
if not any('S88' in l for l in bl):
    print('FAIL: M190 S88 A nicht im G-Code', file=sys.stderr); sys.exit(1)
print('  bed B initial=88 →', next(l for l in bl if 'S88' in l))

# 3) retraction_length
rv = set(re.findall(r'G1 E(-[0-9.]+)', open('${TMP}/fr.gcode').read()))
if '-2.4' not in rv and '-2.400' not in rv:
    print('FAIL: G1 E-2.4 nicht im G-Code', file=sys.stderr)
    print('  gefundene retract-Werte:', sorted(rv)[:5], file=sys.stderr); sys.exit(1)
print('  retract=2.4 → G1 E-2.4 vorhanden')

print('PASS (Phase 4.4 Filament-Overrides)')
PY
