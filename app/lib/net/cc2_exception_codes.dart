// Lookup: liefert einen bekannten Text (sprach-abhaengig) oder null.
// Fallback-Formatierung liegt beim Caller (meist AppLocalizations.
// exceptionCodeUnknown(code)), damit die Lokalisierung konsistent
// aus dem UI-Context kommt.
String? cc2ExceptionLookup(int code, {required String locale}) {
